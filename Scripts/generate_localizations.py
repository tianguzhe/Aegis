#!/usr/bin/env python3
"""Compile the source String Catalog to portable SwiftPM .strings resources.

Xcode compiles catalogs itself; native SwiftPM on CI does not. The catalog stays
the only editable source and generated resources are checked for drift in CI.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "Packages/AegisKit/Sources/AegisCore/Resources"


def generate(check=False):
    catalog = json.loads((RESOURCES / "Localizable.xcstrings").read_text())
    locales = {}
    for key, entry in sorted(catalog["strings"].items()):
        for locale, translation in entry.get("localizations", {}).items():
            if "stringUnit" not in translation:
                raise ValueError(f"{locale}/{key}: unsupported variation; add stringsdict generation before using it")
            value = translation["stringUnit"]["value"]
            locales.setdefault(locale, []).append(f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};")
    changed = []
    for locale, lines in locales.items():
        destination = RESOURCES / f"{locale}.lproj/Localizable.strings"
        source = "/* Generated by Scripts/generate_localizations.py. Edit Localizable.xcstrings. */\n" + "\n".join(lines) + "\n"
        if not destination.exists() or destination.read_text() != source:
            changed.append(str(destination.relative_to(ROOT)))
            if not check:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(source)
    if check and changed:
        raise SystemExit("Stale localization resources; run python3 Scripts/generate_localizations.py:\n" + "\n".join(changed))
    print(f"{'Checked' if check else 'Generated'} {len(locales)} locale(s) from String Catalog.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
